#!/bin/bash
set -eo pipefail

# ---------------------------------------------------------------------------
# 1. Deterministic feature detection.
#
# configure.ac:44-50 probes optional libraries with AC_CHECK_LIB and bakes
# whatever it finds into BOTH $PREFIX/include/config.h (HAVE_LIBFOO) and the
# @LIBS@ of the installed makemcsim* scripts.  Six of the seven probes test for
# the symbol `main` -- which the probe program itself defines -- so each one
# degenerates to "is libfoo.so lying around on the link path" and succeeds on
# any container that happens to carry it.  Left alone, the shipped makemcsim
# scripts would depend on incidental build-container contents.
#
# This is a numerical-correctness switch, not merely a reproducibility one:
# sim/random.h:38 picks SEED_DEFAULT 0 under HAVE_LIBGSL and 314159265.3589793
# otherwise, so a stray libgsl.so silently changes simulation results.
#
# A pre-set autoconf cache var short-circuits the link test AND still runs the
# "#define HAVE_LIBFOO" / LIBS="-lfoo $LIBS" branch, so config.h and @LIBS@
# stay coherent by construction.
#
# Names recovered with:
#   tar -xOf mcsim-6.2.0.tar.gz mcsim-6.2.0/configure \
#     | grep -oE 'ac_cv_lib_[A-Za-z0-9_]+' | sort -u
# (ac_cv_lib_dl_dlopen / dld_* / svld_* are libtool non-Linux branches.)
#
# NB: passing LIBS=-lm does NOT achieve this.  Verified in the generated
# configure: AC_CHECK_LIB saves and restores LIBS around each probe, then
# *prepends* -lfoo on success regardless of what LIBS was seeded with.
export ac_cv_lib_lapack_main=no
export ac_cv_lib_sundials_nvecserial_main=no
export ac_cv_lib_sundials_cvodes_main=no
export ac_cv_lib_gslcblas_main=no
export ac_cv_lib_gsl_gsl_cdf_gamma_P=no
export ac_cv_lib_sbml_main=no
export ac_cv_lib_m_main=yes   # always present; pins baked @LIBS@ to exactly "-lm"

# Autoconf 2.69's AC_FUNC_MALLOC/AC_FUNC_REALLOC (configure.ac:61-62) define
# rpl_malloc/rpl_realloc when the glibc-ism test fails to compile, and no
# malloc.c is shipped -- MacPorts hits this and patches configure.ac for clang.
# Harmless on glibc, set unconditionally so a future osx build cannot regress.
export ac_cv_func_malloc_0_nonnull=yes
export ac_cv_func_realloc_0_nonnull=yes

# ---------------------------------------------------------------------------
# 2. Never let make try to rebuild the Texinfo manual.
#
# doc/Makefile.in carries "$(srcdir)/mcsim.info: mcsim.texi" and INFO_DEPS
# points at the shipped doc/mcsim.info.  With texinfo absent, automake's
# "missing" wrapper propagates exit status 127 and the build FAILS outright
# (missing's last statement is "exit $st").  The shipped .info is already 4
# minutes newer than the .texi, so the rule normally does not fire -- make that
# luck unconditional rather than dependent on extractor timestamps.
# There is no --disable flag for this, and MAKEINFO=true would be worse: it
# would truncate the real manual to a stub if the rule ever did fire.
touch doc/mcsim.info

# ---------------------------------------------------------------------------
# 3. Configure.
#
# Do NOT autoreconf: configure is shipped, executable, pre-generated by Autoconf
# 2.69, and AM_INIT_AUTOMAKE([-Wall -Werror]) turns any warning from a newer
# automake into a hard error.  In-tree build (the default) so that automake's
# $(srcdir)/config.h lookup sees the regenerated header.
#
# --with-mpi=no forecloses AX_PROG_CC_MPI's default of `auto`, which would
# silently enable makemcsimp against an MPI that is not a runtime dependency
# should a stray mpicc ever appear on PATH.
./configure \
    --prefix="$PREFIX" \
    --with-mpi=no \
    --disable-static \
    --disable-dependency-tracking

make -j"${CPU_COUNT}"
make install

# ---------------------------------------------------------------------------
# 4. Post-install fixups.
#
# $PREFIX/include/config.h is REQUIRED, not cruft: nothing in the tree uses
# HAVE_CONFIG_H (zero hits), so the installed headers sim/random.h:30 and
# sim/mh.h:35 include it unguarded, and makemcsims/makemcsimd compile
# $PREFIX/share/mcsim/sim/*.c against -I$PREFIX/include.  Deleting it breaks
# every user model build.  The tarball also ships a STALE author-built config.h
# (HAVE_LIBSBML / HAVE_LIBSUNDIALS_CVODES / HAVE_LIBGSL all =1) that
# include_HEADERS could prefer, so re-assert ours unconditionally.
cp -f config.h "${PREFIX}/include/config.h"

# Nothing links through libmcsim.la: makemcsim calls plain ${CC} ... -lmcsim,
# and makemcsims/makemcsimd recompile the installed sources directly.
# --disable-static already suppressed the archive; the rm is belt-and-braces.
rm -f "${PREFIX}"/lib/libmcsim.la "${PREFIX}"/lib/libmcsim.a

# Keep: $PREFIX/share/mcsim/sim/  (makemcsims/makemcsimd compile these at user
#       time), $PREFIX/include/{config.h + 11 headers}, $PREFIX/share/info.

# ---------------------------------------------------------------------------
# 5. Invariant assertions.
#
# config.h and the baked @LIBS@ must agree, or user model compiles fail to link
# (or silently change behaviour).  Lint/render cannot exercise any of section 1,
# so fail the BUILD loudly if the cache vars ever stop taking effect.
if grep -q '#define HAVE_LIBGSL 1' "${PREFIX}/include/config.h"; then
  grep -q -- '-lgsl' "${PREFIX}/bin/makemcsim" \
    || { echo "ERROR: config.h defines HAVE_LIBGSL but makemcsim does not link -lgsl"; exit 1; }
fi
if grep -q '#define HAVE_LIBSBML 1' "${PREFIX}/include/config.h"; then
  grep -q -- '-lsbml' "${PREFIX}/bin/makemcsim" \
    || { echo "ERROR: config.h defines HAVE_LIBSBML but makemcsim does not link -lsbml"; exit 1; }
fi
# This build is deliberately libc/libm-only.
if grep -Eq -- '-l(gsl|lapack|sbml|sundials)' "${PREFIX}/bin/makemcsim"; then
  echo "ERROR: nondeterministic optional-library detection crept into @LIBS@:"
  grep -E -- '-l(gsl|lapack|sbml|sundials)' "${PREFIX}/bin/makemcsim"
  exit 1
fi

# ---------------------------------------------------------------------------
# 6. End-to-end functional gate.
#
# Deliberately here rather than in meta.yaml's test: section -- this is the only
# place a C compiler is guaranteed to exist, and conda-forge's c-compiler
# metapackage explicitly forbids its use as a recipe dependency.
#
# Upstream's own `make check` is NOT used: examples/perc/Makefile:34 hardcodes
# the author's box (gcc, -I/usr/local/include, -lsbml -lgsl -lmpi -llapack).
rm -rf "${SRC_DIR}/smoke"
mkdir -p "${SRC_DIR}/smoke"
(
  cd "${SRC_DIR}/smoke"
  cp "${SRC_DIR}/examples/perc/perc.model" .
  cp "${SRC_DIR}/examples/perc/perc.lsodes.in" .
  PATH="${PREFIX}/bin:${PATH}" makemcsim perc.model mcsim.perc
  test -x ./mcsim.perc
  # Proves the -Wl,-rpath,@prefix@/lib mitigation, without LD_LIBRARY_PATH.
  # Matched on the versioned name because that is the real SONAME libtool emits
  # (libmcsim.so.0); matching "libmcsim.so" would pass only as a substring.
  ldd ./mcsim.perc | grep -F "${PREFIX}/lib/libmcsim.so.0"
  ./mcsim.perc perc.lsodes.in sim.out
  test -s sim.out
  # Column headers as they appear in examples/perc/perc.lsodes.out.
  grep -q 'C_exh_ug' sim.out
)

# makemcsimp must self-disable cleanly (built --with-mpi=no).
if "${PREFIX}/bin/makemcsimp" >/dev/null 2>&1; then
  echo "ERROR: makemcsimp succeeded although this package was built --with-mpi=no"
  exit 1
fi
